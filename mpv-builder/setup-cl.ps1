# LGPL libmpv only: -Dgpl=false, no cplayer, every GPL-gated feature (cdda, dvbin, dvda, dvdnav,
# direct3d, ...) explicitly disabled so meson fails loudly instead of silently re-enabling them.
$nativeFile = if ($env:ARCH -eq 'arm64') { '../windows-clangcl-arm64.ini' } else { '../windows-clangcl.ini' }
meson setup build `
    --wrap-mode=nodownload  `
    --force-fallback-for=libplacebo  `
    --native-file=$nativeFile  `
    -Dgpl=false `
    -Dlibmpv=true `
    -Dcplayer=false `
    -Dwin32-smtc=disabled `
    -Dd3d11=enabled `
    -Dd3d-hwaccel=enabled `
    -Ddirect3d=disabled `
    -Diconv=enabled `
    -Duchardet=enabled `
    -Dlua=luajit `
    -Djavascript=enabled `
    -Dcplugins=disabled `
    -Drubberband=disabled `
    -Dvapoursynth=disabled `
    -Dlibarchive=disabled `
    -Dlibbluray=disabled `
    -Dlibcurl=disabled `
    -Dcdda=disabled `
    -Ddvbin=disabled `
    -Ddvda=disabled `
    -Ddvdnav=disabled `
    -Ddrm=disabled `
    -Dzimg=disabled `
    -Djpeg=enabled  `
    -Dgl=disabled `
    -Dvaapi=disabled `
    -Dd3d9-hwaccel=disabled  `
    -Dcuda-hwaccel=disabled `
    -Dvulkan=disabled  `
    -Dx11=disabled  `
    -Dwayland=disabled `
    -Dtests=false `
    -Dmanpage-build=disabled `
    -Dlibplacebo:demos=false `
    -Dlibplacebo:lcms=enabled `
    -Dlibplacebo:shaderc=enabled `
    -Dlibplacebo:vulkan=disabled `
    -Dlibplacebo:d3d11=enabled `
    -Dlibplacebo:gl-proc-addr=disabled `
    -Dlibplacebo:opengl=disabled `
    -Dlibplacebo:dovi=enabled `
    -Dlibplacebo:unwind=disabled `
    -Dbuildtype=release  `
    --reconfigure
if ($LASTEXITCODE -ne 0) { throw "meson setup failed ($LASTEXITCODE)" }
